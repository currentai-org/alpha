/**
 * Token build — turns the TS sources (`scales.ts`, `themes.ts`) into:
 *
 *   generated/tokens.css   the runtime custom properties (checked in; imported by the app)
 *   generated/tokens.json  a W3C DTCG token file (Figma / Tokens Studio / Style Dictionary)
 *
 * Pure functions only — `scripts/ds-tokens.mjs` writes the files, `tokens.spec.ts` rebuilds in
 * memory and fails on drift, and the theme playground calls `themeDeclarations()` at runtime.
 *
 * Colour strategy: every semantic colour is ONE declaration, `light-dark(<light>, <dark>)`.
 * Mode is then just `color-scheme` — set by `[data-mode]` or inherited from the OS when the mode
 * is "system" — so light/dark switching needs no JS, no class swap and no duplicate rule blocks,
 * and a subtree can flip mode on its own (the footprint hover card). Custom properties holding
 * `light-dark()` resolve where they are USED, against the element's own color-scheme.
 */
import { deriveTheme, SEMANTIC_TOKENS, type DerivedTheme } from './color/derive.ts';
import { formatOklch } from './color/oklch.ts';
import * as scales from './scales.ts';
import { TAILWIND_COLORS } from './tailwind-map.ts';
import { alphaTheme, themes, STRUCTURE_TOKENS, type ThemeSeeds } from './themes.ts';

export { TAILWIND_COLORS };

export const PREFIX = '--ds-';

type Decl = [name: string, value: string];

export function structuralDeclarations(): Decl[] {
	const out: Decl[] = [];
	for (const [k, v] of Object.entries(scales.fonts)) out.push([`font-${k}`, v]);
	for (const [k, v] of Object.entries(scales.fontWeights)) out.push([`weight-${k}`, v]);
	for (const [k, v] of Object.entries(scales.textSizes)) {
		out.push([`text-${k}`, v.size], [`leading-${k}`, v.lineHeight]);
	}
	for (const [k, v] of Object.entries(scales.tracking)) out.push([`tracking-${k}`, v]);
	for (const [k, v] of Object.entries(scales.radii)) out.push([`radius-${k}`, v]);
	for (const [k, v] of Object.entries(scales.borderWidths)) out.push([`border-${k}`, v]);
	for (const [k, v] of Object.entries(scales.space)) out.push([`space-${k.replace('.', '_')}`, v]);
	for (const [k, v] of Object.entries(scales.controlSizes)) out.push([`control-${k}`, v]);
	for (const [k, v] of Object.entries(scales.layout)) out.push([k, v]);
	for (const [k, v] of Object.entries(scales.motion)) out.push([k, v]);
	for (const [k, v] of Object.entries(scales.zIndex)) out.push([`z-${k}`, v]);
	out.push(['focus-width', scales.focus.width], ['focus-offset', scales.focus.offset]);
	out.push(['ui-font', scales.uiType.font], ['ui-case', scales.uiType.case]);
	for (const [k, v] of Object.entries(scales.shadows)) out.push([`shadow-${k}`, v]);
	for (const [k, v] of Object.entries(scales.xray)) out.push([`xray-${k}`, v]);
	return out;
}

export function colorDeclarations(derived: DerivedTheme): Decl[] {
	return SEMANTIC_TOKENS.map(({ name }) => [
		name,
		`light-dark(${formatOklch(derived.light[name])}, ${formatOklch(derived.dark[name])})`
	]);
}

/** Declarations for one theme, as `--ds-*: value` pairs — used by the runtime playground. */
export function themeDeclarations(theme: ThemeSeeds): Record<string, string> {
	return Object.fromEntries(colorDeclarations(deriveTheme(theme)).map(([k, v]) => [PREFIX + k, v]));
}

/** Every `--ds-*` custom property the system defines. The lint rule `no-unknown-tokens` reads this. */
export function tokenManifest(): string[] {
	return [
		...structuralDeclarations().map(([k]) => PREFIX + k),
		...SEMANTIC_TOKENS.map((t) => PREFIX + t.name),
		...CONTEXTUAL_TOKENS.map((t) => PREFIX + t)
	];
}

/**
 * Contextual (surface-aware) tokens. A `[data-surface]` ancestor sets what "the surface I'm on"
 * means, so components can follow the spec's placement rules without knowing where they render:
 *
 *   - a bordered button's rest fill is ONE TIER UP from whatever is behind it (never the same);
 *   - a rule on Background 3 steps up to Border 3.
 */
export const CONTEXTUAL_TOKENS = ['surface', 'surface-raised', 'surface-line'] as const;

const SURFACE_CONTEXTS: Record<string, Record<(typeof CONTEXTUAL_TOKENS)[number], string>> = {
	'1': {
		surface: 'var(--ds-bg-1)',
		'surface-raised': 'var(--ds-bg-2)',
		'surface-line': 'var(--ds-line-2)'
	},
	'2': {
		surface: 'var(--ds-bg-2)',
		'surface-raised': 'var(--ds-bg-3)',
		'surface-line': 'var(--ds-line-2)'
	},
	'3': {
		surface: 'var(--ds-bg-3)',
		'surface-raised': 'var(--ds-bg-2)',
		'surface-line': 'var(--ds-line-3)'
	},
	chrome: {
		surface: 'var(--ds-bg-chrome)',
		'surface-raised': 'var(--ds-bg-1)',
		'surface-line': 'var(--ds-line-2)'
	}
};

const block = (selector: string, decls: Decl[], indent = '\t') =>
	`${selector} {\n${decls.map(([k, v]) => `${indent}${k.startsWith('--') ? k : PREFIX + k}: ${v};`).join('\n')}\n}`;

export function buildCss(): string {
	const derived = deriveTheme(alphaTheme);
	const parts: string[] = [
		`/*\n * GENERATED by \`pnpm ds:tokens\` from packages/alpha-ds/src/tokens/{scales,themes}.ts — do not edit.\n * Drift is a test failure (tokens.spec.ts).\n */`,
		'',
		'/* Structural + colour tokens. Defined on :root so any surface may opt in; they have no',
		'   visual effect until referenced. Mode is decided by color-scheme (see .ds-root below). */',
		block(':root', [...structuralDeclarations(), ...colorDeclarations(derived)]),
		''
	];

	// Every theme — the default included — gets a complete block: all colours plus every structural
	// token a theme may override (its own value, else the default). So a subtree can re-theme inside
	// another theme (the Appearance cards preview each theme inside the window's current one) without
	// inheriting the outer theme's corners or type.
	const defaults = new Map(structuralDeclarations());
	for (const theme of themes) {
		const structure = STRUCTURE_TOKENS.map((name): Decl => [
			name,
			theme.structure?.[name] ?? defaults.get(name) ?? ''
		]);
		parts.push(
			`/* Theme: ${theme.label} */`,
			block(`[data-ds-theme='${theme.id}']`, [
				...colorDeclarations(deriveTheme(theme)),
				...structure
			]),
			''
		);
	}

	parts.push(
		'/* Mode. "system" (no data-mode) follows the OS; an explicit mode pins it for the subtree. */',
		'.ds-root {\n\tcolor-scheme: light dark;\n}',
		".ds-root[data-mode='light'],\n.ds-root [data-mode='light'] {\n\tcolor-scheme: light;\n}",
		".ds-root[data-mode='dark'],\n.ds-root [data-mode='dark'] {\n\tcolor-scheme: dark;\n}",
		'',
		'/* Surface context — see CONTEXTUAL_TOKENS in build.ts. */'
	);
	parts.push(
		block(
			`:root,\n.ds-root,\n[data-ds-theme],\n[data-surface='1']`,
			Object.entries(SURFACE_CONTEXTS['1']).map(([k, v]) => [k, v])
		)
	);
	for (const key of ['2', '3', 'chrome']) {
		parts.push(
			block(
				`[data-surface='${key}']`,
				Object.entries(SURFACE_CONTEXTS[key]).map(([k, v]) => [k, v])
			)
		);
	}
	parts.push(
		'/* Chrome (the top bar) is an always-dark island in both modes (spec: "pure black"). Flipping',
		'   color-scheme re-resolves every light-dark() token inside it, so text, rules and controls',
		'   placed on the bar are legible without any chrome-specific classes. */',
		"[data-surface='chrome'] {\n\tcolor-scheme: dark;\n}"
	);
	parts.push(
		'',
		'@media (prefers-reduced-motion: reduce) {',
		block(
			'\t:root',
			[
				['duration-fast', '0ms'],
				['duration-base', '0ms'],
				['duration-slow', '0ms']
			],
			'\t\t'
		).replace(/\n}$/, '\n\t}'),
		'}',
		''
	);
	return parts.join('\n');
}

/**
 * Tailwind v4 bridge: `@theme inline` registrations so tokens are reachable as utilities
 * (`bg-surface-2`, `text-fg-3`, `border-line-2`, `rounded-field`, `text-body`, `max-w-thread`),
 * plus one `type-*` utility per composite type role. `inline` keeps each utility pointing at the
 * live `--ds-*` variable, so theme/mode changes never need a rebuild.
 */
export function buildTailwind(): string {
	const lines: string[] = [
		`/*\n * GENERATED by \`pnpm ds:tokens\` from packages/alpha-ds/src/tokens/{scales,build}.ts — do not edit.\n * Tailwind utilities for the Alpha design system. Values stay live CSS variables (@theme inline).\n */`,
		'',
		'@theme inline {'
	];
	for (const [utility, token] of Object.entries(TAILWIND_COLORS)) {
		lines.push(`\t--color-${utility}: var(${PREFIX}${token});`);
	}
	for (const k of Object.keys(scales.xray))
		lines.push(`\t--color-xray-${k}: var(${PREFIX}xray-${k});`);
	for (const k of Object.keys(scales.radii))
		lines.push(`\t--radius-${k}: var(${PREFIX}radius-${k});`);
	for (const k of Object.keys(scales.textSizes)) {
		lines.push(`\t--text-${k}: var(${PREFIX}text-${k});`);
		lines.push(`\t--text-${k}--line-height: var(${PREFIX}leading-${k});`);
	}
	for (const k of Object.keys(scales.controlSizes))
		lines.push(`\t--spacing-control-${k}: var(${PREFIX}control-${k});`);
	lines.push(
		`\t--spacing-sidebar: var(${PREFIX}sidebar-width);`,
		`\t--spacing-rail: var(${PREFIX}sidebar-rail-width);`,
		`\t--spacing-header: var(${PREFIX}header-height);`,
		`\t--spacing-side-panel: var(${PREFIX}side-panel-width);`,
		// The marketing site's fixed header height, so full-height DS surfaces can clear it.
		'\t--spacing-site-header: var(--nav-bar-offset, 0px);',
		`\t--container-thread: var(${PREFIX}thread-width);`,
		`\t--shadow-window: var(${PREFIX}shadow-window);`,
		`\t--shadow-popover: var(${PREFIX}shadow-popover);`,
		`\t--ease-standard: var(${PREFIX}ease-standard);`,
		`\t--ease-exit: var(${PREFIX}ease-exit);`,
		'}',
		''
	);
	for (const k of Object.keys(scales.zIndex)) {
		lines.push(`@utility z-${k} {\n\tz-index: var(${PREFIX}z-${k});\n}`);
	}
	lines.push('');
	for (const [name, style] of Object.entries(scales.typeStyles)) {
		const decls = [
			`font-family: var(${PREFIX}${style.font === 'ui' ? 'ui-font' : `font-${style.font}`});`,
			`font-size: var(${PREFIX}text-${style.size});`,
			`line-height: ${'lineHeight' in style ? style.lineHeight : `var(${PREFIX}leading-${style.size})`};`,
			`font-weight: var(${PREFIX}weight-${style.weight});`,
			`letter-spacing: var(${PREFIX}tracking-${style.tracking});`
		];
		if ('uppercase' in style && style.uppercase)
			decls.push(`text-transform: var(${PREFIX}ui-case);`);
		lines.push(`@utility type-${name} {\n${decls.map((d) => '\t' + d).join('\n')}\n}`);
	}
	lines.push('');
	return lines.join('\n');
}

/** The token manifest as JSON — read by the design linter (`no-unknown-tokens`) without importing TS. */
export function buildManifest(): string {
	return (
		JSON.stringify(
			{ tokens: tokenManifest(), tailwindColors: Object.keys(TAILWIND_COLORS) },
			null,
			'\t'
		) + '\n'
	);
}

/** W3C Design Tokens Community Group format (2025.10 stable draft). */
export function buildDtcg(): Record<string, unknown> {
	const color: Record<string, unknown> = {};
	for (const theme of themes) {
		const d = deriveTheme(theme);
		const entry: Record<string, unknown> = {};
		for (const t of SEMANTIC_TOKENS) {
			entry[t.name] = {
				$type: 'color',
				$description: t.description,
				$value: formatOklch(d.light[t.name]),
				$extensions: {
					'org.aipotluck.modes': {
						light: formatOklch(d.light[t.name]),
						dark: formatOklch(d.dark[t.name])
					}
				}
			};
		}
		color[theme.id] = entry;
	}
	const dim = (obj: Record<string, string>) =>
		Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, { $type: 'dimension', $value: v }]));
	return {
		$description: 'Alpha design system tokens. Generated — edit packages/alpha-ds/src/tokens/*.ts.',
		color,
		font: Object.fromEntries(
			Object.entries(scales.fonts).map(([k, v]) => [k, { $type: 'fontFamily', $value: v }])
		),
		fontWeight: Object.fromEntries(
			Object.entries(scales.fontWeights).map(([k, v]) => [
				k,
				{ $type: 'fontWeight', $value: Number(v) }
			])
		),
		fontSize: Object.fromEntries(
			Object.entries(scales.textSizes).map(([k, v]) => [k, { $type: 'dimension', $value: v.size }])
		),
		lineHeight: Object.fromEntries(
			Object.entries(scales.textSizes).map(([k, v]) => [
				k,
				{ $type: 'dimension', $value: v.lineHeight }
			])
		),
		radius: dim(scales.radii),
		borderWidth: dim(scales.borderWidths),
		space: dim(scales.space),
		controlSize: dim(scales.controlSizes),
		layout: dim(scales.layout),
		duration: Object.fromEntries(
			Object.entries(scales.motion)
				.filter(([k]) => k.startsWith('duration'))
				.map(([k, v]) => [k.replace('duration-', ''), { $type: 'duration', $value: v }])
		)
	};
}
