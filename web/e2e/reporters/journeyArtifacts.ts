// playwright.config.ts sets no `outputDir`, so a recording lands at a path built from the
// spec's filename and the test's title string (`test-results/<spec>-<title>-<project>/video.webm`).
// Renaming a test moves its whole artifact history, and nothing groups the recordings that share a
// journey tag (`@A1`, `@F2`, ...) under that journey. A critique pass — or a human — asking "what is
// the current recording for A1" has to guess a path from prose to answer that.
//
// This reporter re-homes each tagged test's finished video to
// test-results/journeys/<JOURNEY>/<test-slug>/video.webm — keyed by test, not by journey alone.
//
// A journey tag is not one test. A1 has 3 tagged tests (sign-in.spec.ts) and A3 has 4
// (data-portability.spec.ts + guest-retention-notice.spec.ts), each walking a different slice of the
// journey doc's step table, and an earlier one-file-per-journey scheme overwrote
// siblings on every run, so the grader graded the WHOLE step table against whichever test finished
// last: steps a sibling test covers were reported as product defects because that sibling's video
// had been discarded.
// Every tagged test now keeps its own recording; critique-journey.mjs reads the whole set per journey.

import { mkdirSync, copyFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Reporter, TestCase, TestResult } from '@playwright/test/reporter';

// The shape journeyStep() (scenarios/helpers/journeyStep.ts) gives a step that walks one row of
// a journey doc. Generated by our own helper, so a title that misses it is a step nobody marked.
export const JOURNEY_STEP_TITLE_RE = /^([A-Z]\d+) step (\d+)\b/;

// The recording starts when its page exists, so a step's place in the video is its start minus the
// end of the first `Create page` call. Checked on Playwright 1.63 with a page that turns
// red and then blue inside two marked steps: each colour change landed within 60 ms of the offset
// this gives. The test's own start is 1.5 s too early (browser launch, context), and the video's
// length does not track wall time (8.68 s of video for a 7.1 s window), so neither end of the run
// is a usable anchor.
const PAGE_CREATED_TITLE = 'Create page';

type StepLike = {
	title: string;
	category: string;
	startTime: Date;
	duration: number;
	steps: StepLike[];
};

export type StepSpan = {
	journey: string;
	row: number;
	title: string;
	/** Milliseconds from the video's first frame. */
	startMs: number;
	endMs: number;
	/** The page's accessibility snapshot when the row's body finished, if one was attached. */
	snapshot?: string;
};

type AttachmentLike = { name: string; body?: Buffer | string; path?: string };

// journeyStep() attaches the snapshot under this name; kept as a literal here so the reporter does not
// import a scenario helper (and @playwright/test with it) into a reporter module.
const SNAPSHOT_NAME_RE = /^journey-step:([A-Z]\d+):(\d+)$/;

// A chat page's snapshot is a few KB; a long conversation can run far past what one row needs. The cap
// keeps meta.json and the grader's prompt bounded, cutting from the middle so the page's opening
// structure and its latest content both survive. It sits above the largest page a journey walks: on
// develop the median of 182 row snapshots was 2.4k characters and the gap map's ran to 42.5k,
// and a 12k cap cut the open category and the gallery's open journey card out of G1's and F9's rows.
export const SNAPSHOT_MAX_CHARS = 48_000;

function capSnapshot(text: string): string {
	if (text.length <= SNAPSHOT_MAX_CHARS) return text;
	const half = Math.floor(SNAPSHOT_MAX_CHARS / 2);
	const cut = text.length - 2 * half;
	return `${text.slice(0, half)}\n… (${cut} characters cut) …\n${text.slice(-half)}`;
}

/** Snapshots journeyStep() attached, per `<journey>:<row>`, in the order they were attached. */
function snapshotsByRow(attachments: readonly AttachmentLike[]): Map<string, string[]> {
	const out = new Map<string, string[]>();
	for (const a of attachments) {
		const m = SNAPSHOT_NAME_RE.exec(a.name);
		if (!m || a.body === undefined) continue;
		const key = `${m[1]}:${m[2]}`;
		out.set(key, [...(out.get(key) ?? []), capSnapshot(a.body.toString())]);
	}
	return out;
}

function flatten(steps: readonly StepLike[]): StepLike[] {
	return steps.flatMap((s) => [s, ...flatten(s.steps ?? [])]);
}

/** Epoch ms of the recording's first frame, or null when the run never created a page. */
export function videoStartOf(steps: readonly StepLike[]): number | null {
	const created = flatten(steps)
		.filter((s) => s.category === 'pw:api' && s.title === PAGE_CREATED_TITLE)
		.sort((a, b) => a.startTime.getTime() - b.startTime.getTime())[0];
	return created ? created.startTime.getTime() + created.duration : null;
}

/** Milliseconds into the video at which the test's first page asked for its first document, from the
 *  `first-navigation` annotation helpers/test.ts adds (CUR-2989). Null without that annotation or a
 *  page, which leaves the opening blank measured from the first frame as before. */
export function navigatedAtOf(
	steps: readonly StepLike[],
	annotations: readonly { type: string; description?: string }[]
): number | null {
	const origin = videoStartOf(steps);
	const stamp = Number(annotations.find((a) => a.type === 'first-navigation')?.description);
	if (origin === null || !Number.isFinite(stamp)) return null;
	return Math.max(0, stamp - origin);
}

// helpers/layoutShifts.ts attaches the page's layout shifts under this name; a literal here
// for the same reason as SNAPSHOT_NAME_RE.
const LAYOUT_SHIFTS_NAME = 'layout-shifts';

type ShiftSource = { node: string | null; from: number[] | null; to: number[] | null };

const shiftRect = (r: unknown): number[] | null =>
	Array.isArray(r) && r.length === 4 && r.every(Number.isFinite) ? (r as number[]) : null;

function shiftSource(s: unknown): ShiftSource {
	const o = (s ?? {}) as Record<string, unknown>;
	return {
		node: typeof o.node === 'string' ? o.node.slice(0, 100) : null,
		from: shiftRect(o.from),
		to: shiftRect(o.to)
	};
}

export type VideoLayoutShift = {
	/** Milliseconds from the video's first frame. */
	atMs: number;
	value: number;
	path: string;
	sources: ShiftSource[];
};

/** The test's layout shifts as offsets into its video, in order. A shift from before the first frame
 *  (a page the recording never showed) is dropped, as is the whole list when the run created no page. */
export function layoutShiftsOf(
	steps: readonly StepLike[],
	attachments: readonly AttachmentLike[] = []
): VideoLayoutShift[] {
	const origin = videoStartOf(steps);
	const body = attachments.find((a) => a.name === LAYOUT_SHIFTS_NAME)?.body;
	if (origin === null || !body) return [];
	let raw: unknown;
	try {
		raw = JSON.parse(body.toString());
	} catch {
		return [];
	}
	if (!Array.isArray(raw)) return [];
	return raw
		.filter((s) => Number.isFinite(s?.at) && Number.isFinite(s?.value))
		.map((s) => ({
			atMs: Math.round(s.at - origin),
			value: Math.round(s.value * 10_000) / 10_000,
			// The page wrote these, so they are clamped before they reach meta.json.
			path: typeof s.path === 'string' ? s.path.slice(0, 200) : '',
			sources: Array.isArray(s.sources) ? s.sources.slice(0, 3).map(shiftSource) : []
		}))
		.filter((s) => s.atMs >= 0)
		.sort((x, y) => x.atMs - y.atMs);
}

/** Every journeyStep() span in the run, as offsets into its video, in the order they ran. A row
 *  walked twice in one test gets its snapshots in attach order, which is the order the rows ran. */
export function stepSpans(
	steps: readonly StepLike[],
	attachments: readonly AttachmentLike[] = []
): StepSpan[] {
	const origin = videoStartOf(steps);
	if (origin === null) return [];
	const snapshots = snapshotsByRow(attachments);
	const spans = flatten(steps)
		.filter((s) => s.category === 'test.step')
		.flatMap((s) => {
			const m = JOURNEY_STEP_TITLE_RE.exec(s.title);
			if (!m) return [];
			const startMs = Math.max(0, s.startTime.getTime() - origin);
			return [
				{
					journey: m[1],
					row: Number(m[2]),
					title: s.title,
					startMs,
					endMs: startMs + s.duration
				}
			];
		})
		.sort((a, b) => a.startMs - b.startMs);
	return spans.map((span): StepSpan => {
		const snapshot = snapshots.get(`${span.journey}:${span.row}`)?.shift();
		return snapshot === undefined ? span : { ...span, snapshot };
	});
}

// `P\d+` is the adversarial-persona series, and it is a separate letter from `A` on
// purpose. The A-series is the product roadmap — "A2. Alpha speaks my language" is a
// commitment with a milestone behind it — so a chaos-monkey run filed as an A-number would answer a
// question that column is not asking. Same pipeline, different namespace.
// Any single capital letter plus digits, rather than the three series that happened to
// exist when this was written. The letters are Linear's own project prefixes — A and F were the only
// ones with journeys, and G1 (the gap map) and W1 (the website) are two more real surfaces with real
// personas. Enumerating them meant the NEXT letter would be dropped in silence, which is the failure
// the warning below now names.
// Exported so taggedOutcomes.ts (CUR-1635) can find the same tests this reporter does, rather than
// keeping a second copy of the pattern that could drift from this one.
export const JOURNEY_TAG_RE = /^@([A-Z]\d+)$/;

// A tag that looks like a journey tag but is not one — wrong case (`@a1`), or a shape this does not
// accept. Worth a warning rather than a silent skip: a mistyped tag produces a test that runs, passes
// and leaves no recording, so the gallery reports the journey as never walked while CI is green. The
// two states a reader is choosing between there are "the journey has no test" and "the journey has a
// test whose tag was dropped", and nothing distinguished them before.
const NEARLY_A_JOURNEY_TAG_RE = /^@[A-Za-z]{1,2}\d+$/;

export const JOURNEYS_DIR = join(process.cwd(), 'test-results', 'journeys');

/** A filesystem- and URL-safe slug from a test's title, stable across runs of the SAME test so a
 *  re-run overwrites its own prior recording rather than accumulating stale directories forever.
 *
 *  This used to claim it "relies on playwright.config.ts's `workers: 1`" — that a retried
 *  test's two attempts could run concurrently above `workers: 1` and race to write this slug. Checked
 *  directly (a throwaway flaky-test experiment, workers:3): attempt 0 always finishes before attempt 1
 *  starts, on a different worker PID, regardless of `workers` — Playwright serializes a test's own
 *  retries by construction, so that was never a real risk. The actual protection against two DIFFERENT
 *  tests colliding on one slug is `recordingSlug` below keying by project as well as title (CUR-1550);
 *  this function alone was never that guarantee. */
export function testSlug(title: string): string {
	const slug = title
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '');
	return (slug || 'test').slice(0, 80);
}

/** The directory name a recording is filed under: the test's slug plus the project that produced it.
 *
 *  The project belongs in the key because a journey is walked on more than one viewport and
 *  the same test title then arrives twice. Keyed on title alone the second arrival silently overwrote
 *  the first, so the grader read one recording, could not tell which viewport it was, and a desktop
 *  pass could be replaced by a mobile failure of the same name. That is CUR-1480's defect at a
 *  different level — there it was sibling tests sharing a journey, here it is one test on two devices.
 *
 *  The project is always in the name, not only when several exist. A name that changes shape
 *  depending on how many projects are configured is a directory listing whose reader cannot tell a
 *  single-viewport run from a truncated multi-viewport one. */
export function recordingSlug(title: string, project: string): string {
	const p = (project || 'unknown')
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '');
	return `${testSlug(title)}--${p || 'unknown'}`;
}

/** Playwright hands the project through the suite tree rather than on the TestCase, and the shape has
 *  moved between versions, so this reads it defensively and names the gap rather than throwing. An
 *  `unknown` in a path is a legible "the reporter could not tell"; a crash here would lose the
 *  recording the run exists to produce. */
export function projectNameOf(test: TestCase): string {
	try {
		return (
			(
				test as unknown as { parent?: { project?: () => { name?: string } | undefined } }
			).parent?.project?.()?.name ?? 'unknown'
		);
	} catch {
		return 'unknown';
	}
}

export default class JourneyArtifactsReporter implements Reporter {
	onTestEnd(test: TestCase, result: TestResult): void {
		// Every journey tag, not the first. A test that walks steps of two journeys used to
		// reach only the first one's grader, so the other journey's doc could name it as coverage, the
		// test could pass, and that journey's grader never received a frame of it. f6-where-alpha-runs.md
		// cited two such tests, tagged @A5 and @F3, and its steps graded inconclusive every run.
		const journeyTags = test.tags.filter((t) => JOURNEY_TAG_RE.test(t));
		if (!journeyTags.length) {
			const nearMiss = test.tags.find(
				(t) => NEARLY_A_JOURNEY_TAG_RE.test(t) && !JOURNEY_TAG_RE.test(t)
			);
			if (nearMiss) {
				console.warn(
					`[journeyArtifacts] "${test.title}" carries ${nearMiss}, which is not a journey tag — no recording was kept and the gallery will report that journey as never walked. Journey tags are one CAPITAL letter and digits, e.g. @A1, @G1.`
				);
			}
			return;
		}
		// A failed run's video is kept on purpose — a failure is exactly the kind of evidence the
		// critique pass (CUR-1464's other half) exists to read.
		const video = result.attachments.find((a) => a.name === 'video' && a.path);
		if (!video?.path) return; // video disabled, or the test crashed before Playwright wrote one

		for (const journeyTag of journeyTags) this.file(test, result, video.path, journeyTag.slice(1));

		// A passing recording now exists only under journeys/. Playwright's copy at the
		// spec-and-title path was never read by anything, and uploading both doubled about 90 MB of
		// every gallery artifact. Removed after the loop, so a test with two journey tags is copied to
		// both first. A failure keeps both copies, because someone debugging it starts from the path
		// Playwright prints.
		if (result.status === 'passed') {
			try {
				unlinkSync(video.path);
			} catch (err) {
				console.warn(`[journeyArtifacts] could not remove ${video.path}: ${String(err)}`);
			}
		}
	}

	private file(test: TestCase, result: TestResult, videoPath: string, journey: string): void {
		const project = projectNameOf(test);
		const destDir = join(JOURNEYS_DIR, journey, recordingSlug(test.title, project));
		mkdirSync(destDir, { recursive: true });
		copyFileSync(videoPath, join(destDir, 'video.webm'));

		writeFileSync(
			join(destDir, 'meta.json'),
			JSON.stringify(
				{
					journey,
					title: test.title,
					// The viewport this recording was taken on. Two recordings of one test differ in
					// nothing else a reader can see, so the page and the grader both need it named
					// rather than inferred from a directory suffix.
					project,
					// Relative to the checkout, because this field is not private to the run: it
					// reaches the gallery manifest and renders on a page. `test.location.file` is
					// absolute, so locally it published a home directory and in CI a runner's
					// scratch path — neither of which means anything to the person reading the card.
					spec: relative(process.cwd(), test.location.file),
					status: result.status,
					// `status` alone reads a `test.fail()` spec's intended failure as "failed",
					// and a reader took the known-bug recording for a flake. Playwright's own verdict rides
					// along: `expectedStatus` is what the spec declared, and `outcome()` is "expected"
					// when the result matched it, so a failed recording with outcome "expected" is the
					// suite working. The annotation's description says which bug it is waiting on.
					expectedStatus: test.expectedStatus,
					outcome: test.outcome(),
					expectedFailureReason:
						test.expectedStatus === 'failed'
							? (test.annotations.find((a) => a.type === 'fail')?.description ?? null)
							: null,
					// 0 on a clean first attempt, 1+ when this recording only exists because an
					// earlier attempt of the SAME test failed. A retried test's later attempt overwrites
					// this same directory (recordingSlug does not vary by attempt), so without this field
					// a flaky test's winning recording is indistinguishable from a first-try pass — the
					// grader judges good footage and finds nothing wrong, which is true of the footage and
					// false about the run that produced it.
					retry: result.retry,
					// This test is a journey's injury proof — it asserts the journey's own checks
					// fail under the fault its title names. Annotated at run time via test.info(), so the
					// result's annotations carry it as well as the test's declared ones.
					injuryProof: [...test.annotations, ...(result.annotations ?? [])].some(
						(a) => a.type === 'injury-proof'
					),
					// The page's own size, from helpers/test.ts. Smaller than the recording's frame
					// when a test narrows the window, and the graders crop to it. Null for a spec that does
					// not import `test` from helpers/test.ts.
					viewport: parseViewport(
						result.annotations?.find((a) => a.type === 'viewport')?.description
					),
					// Numbers the spec measured about the product (helpers/measurement.ts), so the
					// card can show the value a check passed with. Empty when the spec measures nothing.
					measurements: parseMeasurements(result.annotations ?? []),
					startedAt: result.startTime.toISOString(),
					durationMs: result.duration,
					// Where each journeyStep() lands in video.webm, so the tour reel cuts one
					// doc row out of a test rather than playing the whole test, and (CUR-2764) what the
					// page said at the end of each row. Empty when the test marks no steps.
					steps: stepSpans(result.steps ?? [], result.attachments ?? []),
					// When the first page first asked for a document, so the graders count the
					// opening blank from there and not from setup the test did before it. The step spans
					// above stay offsets from the first frame.
					navigatedAtMs: navigatedAtOf(result.steps ?? [], result.annotations ?? []),
					// The page's layout shifts, placed in the video. Capture-only.
					layoutShifts: layoutShiftsOf(result.steps ?? [], result.attachments ?? []),
					// The test's tags, so a grader can tell a recording of the local sign-in leg
					// (@local-mock, a CI runner's localhost) from one of develop.
					tags: test.tags
				},
				null,
				2
			) + '\n'
		);

		// A persona spec attaches the turn-by-turn record of what it chose and why. Frames
		// alone cannot say whether a click landed on what the persona asked for or on a neighbour, so
		// a reviewer watching the video without this has to infer intent from pixels. Copied next to
		// the video rather than left in Playwright's own attachment tree, because everything
		// downstream of here addresses a run by `journeys/<J>/<slug>/` and nothing else knows where
		// Playwright put it. Absent for every non-persona journey, which is why this is conditional
		// rather than required.
		// Matched on `path` OR `body`, because Playwright fills exactly one of them and which one
		// depends on how the test attached it: `testInfo.attach({path})` hands the reporter a file,
		// `testInfo.attach({body})` hands it a Buffer and leaves `path` undefined. A `&& a.path`
		// filter here looked right, ran green, and silently produced no trace at all on the first
		// live run — the video landed, the test passed, and the artifact this clause exists to
		// write was simply absent.
		const trace = result.attachments.find((a) => a.name === 'persona-trace');
		if (trace?.path) copyFileSync(trace.path, join(destDir, 'persona-trace.json'));
		else if (trace?.body) writeFileSync(join(destDir, 'persona-trace.json'), trace.body);
	}
}

type Measurement = { name: string; value: number; unit: string; detail?: string };

/** The `measurement` annotations helpers/measurement.ts writes. One that does not parse to a name, a
 *  finite value and a unit is dropped, since a card showing "NaN" or a blank unit misleads more than
 *  one showing nothing. */
export function parseMeasurements(
	annotations: readonly { type: string; description?: string }[]
): Measurement[] {
	const out: Measurement[] = [];
	for (const a of annotations) {
		if (a.type !== 'measurement') continue;
		let m: unknown;
		try {
			m = JSON.parse(a.description ?? '');
		} catch {
			continue;
		}
		const { name, value, unit, detail } = (m ?? {}) as Record<string, unknown>;
		if (typeof name !== 'string' || !name || typeof unit !== 'string' || !unit) continue;
		if (typeof value !== 'number' || !Number.isFinite(value)) continue;
		out.push(
			typeof detail === 'string' && detail ? { name, value, unit, detail } : { name, value, unit }
		);
	}
	return out;
}

function parseViewport(description: string | undefined): { width: number; height: number } | null {
	const m = /^(\d+)x(\d+)$/.exec(description ?? '');
	return m ? { width: Number(m[1]), height: Number(m[2]) } : null;
}
