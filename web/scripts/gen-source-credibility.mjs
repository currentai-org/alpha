#!/usr/bin/env node
// Regenerates src/lib/chat/search/sourceCredibilityHosts.ts from its two public sources (CUR-2423):
//
//   - Wikipedia's perennial sources list (WP:RSP, CC BY-SA 4.0): every row rated generally unreliable
//     or deprecated. Rows scoped to a topic or a date range ("Fox News (politics and science)", "CNET
//     (November 2022–present)") are skipped, because a host-level filter cannot honour the scope.
//     Rows RSP rates for hosting user-generated content are not taken as "low credibility" wholesale:
//     RSP rates Wikipedia, arXiv and Stack Exchange that way for citing purposes, and they are good
//     evidence for an answer. Only the forum, social and self-publishing platforms in USER_POSTED
//     below are dropped as user-posted.
//   - Iffy.news's index of unreliable sources (CC BY 4.0), its published sheet.
//
// Run: node scripts/gen-source-credibility.mjs   (network; writes the module and prints counts)

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../src/lib/chat/search/sourceCredibilityHosts.ts");
const RSP_PAGES = 8;
const RSP_URL = (n) =>
	`https://en.wikipedia.org/w/index.php?title=Wikipedia:Reliable_sources/Perennial_sources/${n}&action=raw`;
const IFFY_URL =
	"https://docs.google.com/spreadsheets/d/1ck1_FZC-97uDLIlvRJDTrGqBk0FuDe9yHkluROgpGS8/gviz/tq?tqx=out:csv&sheet=Iffy-news";

// Forums, social networks and self-publishing hosts. Each is rated generally unreliable by WP:RSP for
// publishing user-generated content, except where noted.
const USER_POSTED = [
	"reddit.com",
	"quora.com",
	"answers.com",
	"facebook.com",
	"instagram.com",
	"tiktok.com",
	"x.com",
	"twitter.com",
	"youtube.com",
	"linkedin.com",
	"medium.com",
	"blogspot.com",
	"wordpress.com",
	"livejournal.com",
	"fandom.com",
	"wikia.com",
	"dailykos.com",
	"patheos.com",
	"urbandictionary.com",
	"knowyourmeme.com",
	"change.org",
	"gofundme.com",
	// Iffy.news rather than RSP:
	"4chan.org",
	"9gag.com",
	"rumble.com",
	"weibo.com",
];

// RSP rows that name no usable host, or a host whose rating is about Wikipedia's own citing practice.
const RSP_SKIP = new Set(["gnis-class", "gns-class", "ScienceDirect topic", "Religious scriptures texts", "Red Ventures"]);

// Hosts our own engines query directly (searchWikipedia, searchArxiv, …). Never filtered: a rating about
// citing them on Wikipedia says nothing about using them as evidence here. Generation fails if one
// lands in either list.
const ENGINE_HOSTS = ["wikipedia.org", "wikinews.org", "wikidata.org", "arxiv.org", "openalex.org", "huggingface.co"];

const HOST_RE = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/;

async function text(url) {
	const res = await fetch(url, { headers: { "user-agent": "AIPotluck/0.1 (contact@aipotluck.org)" } });
	if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
	return res.text();
}

function rspRows(wiki) {
	return wiki
		.split(/\n\|- class="/)
		.slice(1)
		.map((chunk) => ({
			id: chunk.match(/id="([^"]+)"/)?.[1] ?? "",
			status: chunk.match(/\{\{WP:RSPSTATUS\|([a-z]+)/)?.[1] ?? "",
			ugc: /user-generated|WP:USERG|self-published|WP:SPS|WP:CIRCULAR/i.test(chunk),
			hosts: [...chunk.matchAll(/\{\{WP:RSPUSES\|([^}]+)\}\}/g)]
				.flatMap((m) => m[1].split("|"))
				.map((d) => d.trim().toLowerCase())
				.filter((d) => HOST_RE.test(d)),
		}));
}

/** Minimal CSV reader for Google's gviz export: every field quoted, no embedded newlines. */
function csvColumn(csv, name) {
	const lines = csv.trim().split("\n");
	const split = (l) => l.slice(1, -1).split('","');
	const idx = split(lines[0]).indexOf(name);
	if (idx < 0) throw new Error(`Iffy sheet has no "${name}" column`);
	return lines.slice(1).map((l) => split(l)[idx]?.trim().toLowerCase() ?? "");
}

const rows = [];
for (let n = 1; n <= RSP_PAGES; n++) rows.push(...rspRows(await text(RSP_URL(n))));
const rspLow = rows.filter(
	(r) => (r.status === "gu" || r.status === "d") && !r.ugc && !r.id.includes("(") && !RSP_SKIP.has(r.id)
);
const iffy = csvColumn(await text(IFFY_URL), "Domain").filter((d) => HOST_RE.test(d));
if (rows.length < 400 || iffy.length < 1000) {
	throw new Error(`source lists look truncated: ${rows.length} RSP rows, ${iffy.length} Iffy domains`);
}

const userPosted = new Set(USER_POSTED);
const low = [...new Set([...rspLow.flatMap((r) => r.hosts), ...iffy])].filter((h) => !userPosted.has(h)).sort();
const leaked = ENGINE_HOSTS.filter((h) => low.includes(h) || userPosted.has(h));
if (leaked.length) throw new Error(`engine hosts landed in a filter list: ${leaked.join(", ")}`);
const today = new Date().toISOString().slice(0, 10);

writeFileSync(
	OUT,
	`// GENERATED by scripts/gen-source-credibility.mjs on ${today}. Do not edit by hand; rerun it.
//
// Low-credibility hosts come from Wikipedia's perennial sources list (WP:RSP, CC BY-SA 4.0,
// https://en.wikipedia.org/wiki/Wikipedia:Reliable_sources/Perennial_sources), rows rated generally
// unreliable or deprecated, and from Iffy.news's index of unreliable sources (CC BY 4.0,
// https://iffy.news/index/). User-posted hosts are the forum, social and self-publishing platforms
// those lists rate unreliable for publishing user-generated content.

export const USER_POSTED_HOSTS: readonly string[] = ${JSON.stringify([...userPosted].sort(), null, "\t")};

export const LOW_CREDIBILITY_HOSTS: readonly string[] = ${JSON.stringify(low, null, "\t")};
`
);
console.log(`wrote ${OUT}: ${userPosted.size} user-posted, ${low.length} low-credibility (${rspLow.length} RSP rows, ${iffy.length} Iffy domains)`);
