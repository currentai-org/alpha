// Write agent-service/api/served_backends.json from the catalog's host table (BACKEND_HOSTS in
// src/lib/chat/routing/catalog.ts). It sits inside agent-service's Docker context (only api/ is copied
// into its image), where proxy.py reads the Swiss set, because Python cannot import TypeScript.
//
//   pnpm gen:served-backends
//
// Rerun it after editing a host row or a host's org. src/lib/chat/routing/servedBackends.spec.ts fails
// while the committed file and the catalog disagree.
import "./setups/harnessEnv"; // FIRST: strip blank scaffold env so `??` reads default correctly
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BACKEND_HOSTS, SWISS_BACKEND_HOSTS, backendOrg } from "../src/lib/chat/routing/catalog";

export const SERVED_BACKENDS_FILE = resolve(
	dirname(fileURLToPath(import.meta.url)),
	"../../agent-service/api/served_backends.json"
);

/** The file's exact text: hosts sorted, so a diff shows one row moving. */
export function servedBackendsJson(): string {
	const hosts = Object.fromEntries(
		Object.keys(BACKEND_HOSTS)
			.sort()
			.map((host) => {
				const known = backendOrg(host);
				if (!known) throw new Error(`no org for ${host}`);
				return [
					host,
					{
						org: known.org.id,
						name: known.org.name,
						...(BACKEND_HOSTS[host].service ? { service: BACKEND_HOSTS[host].service } : {}),
						...(known.country ? { country: known.country } : {}),
						swiss: known.swiss,
					},
				];
			})
	);
	const doc = {
		$comment:
			"GENERATED by `pnpm gen:served-backends` from BACKEND_HOSTS in src/lib/chat/routing/catalog.ts. Do not edit: change the catalog and rerun. swissHosts are the hosts whose org region is Switzerland, the backends an answer may come from while 'sovereign public compute in Switzerland' stays true.",
		swissHosts: [...SWISS_BACKEND_HOSTS],
		hosts,
	};
	return JSON.stringify(doc, null, "\t") + "\n";
}

// `--write` rather than a main-module check: under vite-node, argv[1] is vite-node's own CLI.
if (process.argv.includes("--write")) {
	writeFileSync(SERVED_BACKENDS_FILE, servedBackendsJson());
	console.log(`wrote ${SERVED_BACKENDS_FILE}`);
}
