import { describe, it, expect, beforeAll } from "vitest";
import sharp from "sharp";
import { makeImageProcessor, convertImage, resizeImage, chooseImageSize } from "./images";
import type { MessageFile } from "$lib/chat/types/Message";

// Every image a user uploads to a multimodal turn goes through makeImageProcessor (reached from
// endpointOai via prepareFiles). captionImage.spec.ts transitively loading sharp's native binding
// proves only that the module RESOLVES, nothing about what it does.
//
// sharp 0.33 → 0.35 changes behaviour on exactly these paths, and a version bump alone would go green
// through all of it without this spec:
//
//   - 0.35 gives `limitInputChannels` a default of 5, so inputs that decoded under 0.33 can throw.
//     makeImageProcessor has no try/catch, so that surfaces as a failed request.
//   - 0.35 retunes lossy AVIF to SSIMULACRA2 `iq` metrics, against chooseImageSize's hardcoded 1/5
//     guess for AVIF (images.ts:189) — the estimate and the encoder can drift apart.
//   - 0.34 changed non-animated GIF output to default no-loop, and "gif" is an output format here.
//
// So these assert observable contracts — requested format out, aspect ratio preserved, byte cap
// respected — rather than golden bytes, which would break on every encoder tweak and teach nothing.
// Fixtures are generated by sharp itself rather than committed, so they track whatever version is
// installed and the spec measures behaviour, not a stale binary.

const PNG = "image/png";
const asFile = (buffer: Buffer, mime: string): MessageFile => ({
	type: "base64",
	name: "probe",
	mime,
	value: buffer.toString("base64"),
});

/** A deterministic non-uniform image; a flat colour would compress to nothing and hide size effects. */
const noisy = (width: number, height: number, channels: 3 | 4 = 3) => {
	const px = Buffer.alloc(width * height * channels);
	for (let i = 0; i < px.length; i++) px[i] = (i * 37 + (i % 251)) % 256;
	return sharp(px, { raw: { width, height, channels } });
};

let small: Buffer;
let wide: Buffer;

beforeAll(async () => {
	small = await noisy(64, 64).png().toBuffer();
	wide = await noisy(1200, 300).png().toBuffer();
}, 30_000);

describe("convertImage", () => {
	// Every format the processor is allowed to emit (images.ts:91). If a sharp bump renames or drops
	// one, this is where it shows up rather than on a user's upload.
	// AVIF is an HEIF-family container, so sharp reads its own AVIF output back as format "heif".
	// Worth knowing rather than smoothing over: images.ts blocklists image/heic and image/heif on
	// INPUT for licence reasons (images.ts:110), so an AVIF this code emits would be refused if a
	// user ever handed it back. Not in scope to change here, but it is a real round-trip asymmetry.
	const readsBackAs: Record<string, string> = { avif: "heif" };

	it.each(["png", "jpeg", "webp", "avif", "tiff", "gif"])(
		"emits real %s bytes that sharp can read back at unchanged dimensions",
		async (format) => {
			const out = await convertImage(sharp(small), `image/${format}`).toBuffer();
			const meta = await sharp(out).metadata();
			expect(meta.format).toBe(readsBackAs[format] ?? format);
			expect(meta.width).toBe(64);
			expect(meta.height).toBe(64);
		},
		30_000
	);

	it("rejects a non-image mime rather than guessing", () => {
		expect(() => convertImage(sharp(small), "application/pdf")).toThrow(/non-image mime/i);
	});

	it("rejects an image format it cannot emit", () => {
		expect(() => convertImage(sharp(small), "image/svg+xml")).toThrow(/unsupported format/i);
	});
});

describe("resizeImage", () => {
	it("fits inside the box and preserves aspect ratio — never stretches to fill", async () => {
		const out = await resizeImage(sharp(wide), 300, 300).toBuffer();
		const meta = await sharp(out).metadata();
		// 1200x300 into a 300x300 box is width-bound: 300x75, not 300x300.
		expect(meta.width).toBe(300);
		expect(meta.height).toBe(75);
	});

	it("DOES enlarge a small image — sharp's fit:inside upscales unless told not to", async () => {
		// Pinning this because the name resizeImage suggests shrink-only and it is not: sharp's
		// withoutEnlargement defaults false, so a 64px source asked for a 4096 box comes back 4096.
		// Safe today only because makeImageProcessor calls this exclusively with a chooseImageSize
		// result, which never exceeds the source. Anyone calling resizeImage directly gets an upscale.
		const out = await resizeImage(sharp(small), 4096, 4096).toBuffer();
		const meta = await sharp(out).metadata();
		expect(meta.width).toBe(4096);
	}, 30_000);

	it("never enlarges through makeImageProcessor, which is the only caller that matters", async () => {
		const { image } = await makeImageProcessor({
			supportedMimeTypes: [PNG],
			preferredMimeType: PNG,
			maxSizeInMB: 5,
			maxWidth: 4096,
			maxHeight: 4096,
		})(asFile(small, PNG));
		const meta = await sharp(image).metadata();
		expect(meta.width).toBe(64);
		expect(meta.height).toBe(64);
	}, 30_000);
});

describe("chooseImageSize", () => {
	const box = { maxWidth: 512, maxHeight: 512, maxSizeInMB: 5 };

	it("scales the longest side down to the box, keeping proportions", () => {
		expect(chooseImageSize({ mime: PNG, width: 2048, height: 1024, ...box })).toEqual({
			width: 512,
			height: 256,
		});
	});

	it("leaves an image that already fits alone", () => {
		expect(chooseImageSize({ mime: PNG, width: 100, height: 50, ...box })).toEqual({
			width: 100,
			height: 50,
		});
	});

	it("shrinks past the box when the byte estimate still exceeds the cap", () => {
		// PNG is estimated at 1/2 of 4 bytes/px, so 512x512 ≈ 0.5MB. Against a 0.1MB cap the loop has
		// to keep going below the dimension box — the byte cap, not the box, is the binding constraint.
		const size = chooseImageSize({ mime: PNG, width: 4096, height: 4096, ...box, maxSizeInMB: 0.1 });
		expect(size.width).toBeLessThan(512);
		expect(size.width).toBe(size.height);
	});

	it("gives AVIF a bigger allowance than PNG at the same cap — the per-format ratio is live", () => {
		const tight = { maxWidth: 4096, maxHeight: 4096, maxSizeInMB: 1 };
		const png = chooseImageSize({ mime: PNG, width: 4096, height: 4096, ...tight });
		const avif = chooseImageSize({ mime: "image/avif", width: 4096, height: 4096, ...tight });
		expect(avif.width).toBeGreaterThan(png.width);
	});

	it("throws rather than returning a 1px image it cannot honour", () => {
		expect(() =>
			chooseImageSize({ mime: "image/tiff", width: 64, height: 64, ...box, maxSizeInMB: 0.0000001 })
		).toThrow(/Failed to resize/i);
	});

	it("throws on a format it has no compression ratio for", () => {
		expect(() => chooseImageSize({ mime: "image/bmp", width: 64, height: 64, ...box })).toThrow(
			/Unsupported image format/i
		);
	});
});

describe("makeImageProcessor", () => {
	const opts = {
		supportedMimeTypes: ["image/png", "image/jpeg", "image/webp"],
		preferredMimeType: "image/png",
		maxSizeInMB: 5,
		maxWidth: 512,
		maxHeight: 512,
	};

	it("passes a supported, in-bounds image through in its own format", async () => {
		const { image, mime } = await makeImageProcessor(opts)(asFile(small, PNG));
		expect(mime).toBe(PNG);
		const meta = await sharp(image).metadata();
		expect(meta.format).toBe("png");
		expect(meta.width).toBe(64);
	}, 30_000);

	it("refuses SVG content declared as image/png, so an upload never reaches the SVG decoder (CUR-4037)", async () => {
		const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"><rect width="2" height="2" fill="red"/></svg>`;
		await expect(makeImageProcessor(opts)(asFile(Buffer.from(svg), PNG))).rejects.toThrow(
			/unsupported image format/i
		);
	}, 30_000);

	it("resizes an oversized image into the box", async () => {
		const { image } = await makeImageProcessor(opts)(asFile(wide, PNG));
		const meta = await sharp(image).metadata();
		expect(meta.width).toBe(512);
		expect(meta.height).toBe(128);
	}, 30_000);

	it("converts an unsupported input to the SMALLEST supported format, not the preferred one", async () => {
		// chooseMimeType falls through to mimesBySizeDesc.findLast (images.ts:146), so an unsupported
		// input lands on webp here even though preferredMimeType is png. preferredMimeType is only
		// returned when NO supported mime appears in that list at all — it is far less load-bearing
		// than its name suggests, and this is the assertion that says so.
		const tiff = await noisy(64, 64).tiff().toBuffer();
		const { image, mime } = await makeImageProcessor(opts)(asFile(tiff, "image/tiff"));
		expect(mime).toBe("image/webp");
		expect((await sharp(image).metadata()).format).toBe("webp");
	}, 30_000);

	it("carries a 4-channel RGBA image through without losing the alpha", async () => {
		// The channel count is what sharp 0.35's limitInputChannels default constrains, so an alpha
		// image round-tripping is the cheapest standing check that ordinary uploads still decode.
		const rgba = await noisy(80, 80, 4).png().toBuffer();
		const { image } = await makeImageProcessor(opts)(asFile(rgba, PNG));
		const meta = await sharp(image).metadata();
		expect(meta.channels).toBe(4);
		expect(meta.hasAlpha).toBe(true);
	}, 30_000);

	it("picks the smallest supported format when the input is over the byte cap", async () => {
		// preferSizeReduction flips chooseMimeType to mimesBySizeDesc's last supported entry — webp
		// here, since avif is not in supportedMimeTypes.
		const { mime } = await makeImageProcessor({ ...opts, maxSizeInMB: 0.001 })(asFile(wide, PNG));
		expect(mime).toBe("image/webp");
	}, 30_000);

	it("refuses a non-image mime", async () => {
		await expect(makeImageProcessor(opts)(asFile(small, "text/plain"))).rejects.toThrow(
			/non-image mime/i
		);
	});

	it("refuses the licence-blocklisted heic/heif even when asked to reduce size", async () => {
		await expect(
			makeImageProcessor({ ...opts, maxSizeInMB: 0.001 })(asFile(small, "image/heic"))
		).rejects.toThrow(/blocklisted/i);
	});
});
